def write(route, html):
    target = ROOT / (route if route == "404.html" else route + "index.html")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html.replace("<!doctype html>", "<!doctype html>\n" + GENERATED, 1), encoding="utf-8")


def render_page(route, title, description, content, post=None):
    missing = route == "404.html"
    active = None if missing else route.split("/", 1)[0]
    root = "/" if missing else "../" * route.count("/") or "./"
    seo = '<meta name="robots" content="noindex">' if missing else metadata(route, title, description, post)
    if route == "search/":
        seo += '\n    <meta name="robots" content="noindex">'
    return template("page").substitute(
        root=root, title=escape(f"{title} | StackedByBayo" if route else f"StackedByBayo | {title}"),
        description=escape(description),
        article_styles=f'    <link rel="stylesheet" href="{root}assets/css/article.css">\n' if post else "",
        article_script=f'    <script src="{root}assets/js/article.js" defer></script>\n' if post else "",
        metadata=seo, navigation=navigation(root, active, bool(post), header=True),
        footer=footer(root, show_wordmark=bool(route)), content=content, body_class=" news-home" if not route else "", main_class="article-main" if post else "platform-main",
    )


def page(route, title, description, content, post=None):
    write(route, render_page(route, title, description, content, post))


def read_posts(collection):
    posts = []
    for path in sorted((ROOT / "content" / collection).glob("*.md")):
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", path.stem):
            raise ValueError(f"Invalid article slug in {path.name}")
        try:
            first, front_matter, body = path.read_text(encoding="utf-8").split("---\n", 2)
            if first:
                raise ValueError("Front matter must start the file")
            post = json.loads(front_matter)
            if post.get("draft"):
                continue
            for field in ("title", "category", "dateTime", "excerpt"):
                if not isinstance(post[field], str) or not post[field].strip():
                    raise ValueError(f"{field} must be a non-empty string")
            if not body.strip():
                raise ValueError("Article body is empty")
            published = date.fromisoformat(post["dateTime"])
            post["dateTime"] = published.isoformat()
            if post.get("updatedTime"):
                updated = date.fromisoformat(post["updatedTime"])
                if updated < published:
                    raise ValueError("updatedTime must be on or after dateTime")
                post["updatedTime"] = updated.isoformat()
            if post.get("articleType") and post["articleType"] not in ARTICLE_TYPES:
                raise ValueError("Unknown articleType")
            details = post.get("security", {})
            if details.get("severity") and not web_url(details.get("severitySource", "")):
                raise ValueError("A severity rating requires a severitySource URL")
        except (KeyError, ValueError, TypeError) as error:
            raise ValueError(f"{path}: {error}") from error
        post.update(url=f"{collection}/{path.stem}/", body=body, date=published,
                    author=post.get("author") or AUTHOR)
        posts.append(post)
    return sorted(posts, key=lambda post: post["date"], reverse=True)


def date_markup(value):
    return f'<time datetime="{value.isoformat()}">{value:%b} {value.day}, {value.year}</time>'


def post_date(post):
    return date_markup(post["date"])


def image(post, css_class, *, preview=False, priority=False, root="./"):
    if preview and (photo := HOME_PHOTOS.get(post["url"])):
        base = f"{root}assets/img/carousel/{photo}"
        sizes = "(max-width: 650px) 94vw, (max-width: 900px) 90vw, 65vw" if priority else "(max-width: 650px) 45vw, 34vw"
        return (f'<img class="{css_class}" src="{base}-720.webp" srcset="{base}-320.webp 320w, '
                f'{base}-720.webp 720w, {base}-1440.webp 1440w" sizes="{sizes}" alt="" '
                + ('fetchpriority="high"' if priority else 'loading="lazy"') + ' decoding="async">')
    if not post.get("image"):
        return ""
    responsive = ""
    if css_class in {"platform-card-image", "news-photo"} and post["image"].startswith("https://images.unsplash.com/"):
        small, medium = (escape(re.sub(r"([?&]w=)\d+", rf"\g<1>{width}", post["image"]))
                         for width in (480, 800))
        if small != medium:
            responsive = f'srcset="{small} 480w, {medium} 800w" sizes="(max-width: 767px) 90vw, (max-width: 1050px) 45vw, 360px" '
    return (f'<img class="{css_class}" src="{escape(post["image"])}" {responsive}'
            f'alt="{escape(post.get("imageAlt", ""))}" loading="lazy" decoding="async">')


