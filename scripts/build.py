def template(name):
    return Template((ROOT / "templates" / f"{name}.html").read_text(encoding="utf-8"))


def metadata(route, title, description, post=None):
    url = ORIGIN + route
    tags = [
        f'<link rel="canonical" href="{escape(url)}">',
        f'<meta property="og:url" content="{escape(url)}">',
        f'<meta property="og:title" content="{escape(title)}">',
        f'<meta property="og:description" content="{escape(description)}">',
        '<meta property="og:site_name" content="StackedByBayo">',
        f'<meta property="og:type" content="{"article" if post else "website"}">',
    ]
    if post:
        tags.append(f'<meta property="article:published_time" content="{post["dateTime"]}">')
        data = {"@context": "https://schema.org", "@type": "BlogPosting",
                "headline": title, "description": description, "mainEntityOfPage": url,
                "datePublished": post["dateTime"],
                "author": {"@type": "Person", "name": post["author"], "url": ORIGIN + "about/"}}
        if post.get("image"):
            tags.append(f'<meta property="og:image" content="{escape(post["image"])}">')
            data["image"] = post["image"]
        tags.append('<script type="application/ld+json">' + json.dumps(data).replace("<", "\\u003c") + "</script>")
    return "\n    ".join(tags)


def navigation(root, active, article_page=False, *, header=False):
    routes = HEADER_NAV if header else NAV
    current = "location" if article_page else "page"
    return "\n            ".join(
        f'<a href="{root}{route if route.startswith("#") else route + "/" if route else ""}"'
        + (f' class="active" aria-current="{current}"' if route == active else "")
        + f'>{escape(label)}'
        + (' <small class="shop-nav-status">Soon</small>' if route == "shop" else "")
        + '</a>'
        for route, label in routes.items()
    )


