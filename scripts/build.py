def metadata(route, title, description, post=None):
    url = ORIGIN + route
    tags = [
        f'<link rel="canonical" href="{escape(url)}">',
        f'<meta property="og:url" content="{escape(url)}">',
        f'<meta property="og:title" content="{escape(title)}">',
        f'<meta property="og:description" content="{escape(description)}">',
        '<meta property="og:site_name" content="StackedByBayo">',
        f'<meta property="og:type" content="{"article" if post else "website"}">',
    ]
    if post:
        data = {"@context": "https://schema.org", "@type": "BlogPosting",
                "headline": post["title"], "description": description, "mainEntityOfPage": url,
                "articleSection": post["category"],
                "author": {"@type": "Organization" if post["author"] == PUBLICATION else "Person",
                           "name": post["author"]}}
        if published := post.get("dateTime"):
            tags.append(f'<meta property="article:published_time" content="{published}">')
            data["datePublished"] = published
        if url := author_url(post):
            data["author"]["url"] = url
        if updated := post.get("updatedTime"):
            tags.append(f'<meta property="article:modified_time" content="{updated}">')
            data["dateModified"] = updated
        if topics := post.get("categories"):
            data["keywords"] = topics
        if post.get("image"):
            image_url = ORIGIN + post["image"].lstrip("/") if post["image"].startswith("/") else post["image"]
            tags.append(f'<meta property="og:image" content="{escape(image_url)}">')
            if alt := post.get("imageAlt"):
                tags.append(f'<meta property="og:image:alt" content="{escape(alt)}">')
            data["image"] = image_url
        tags.append('<script type="application/ld+json">' + json.dumps(data).replace("<", "\\u003c") + "</script>")
    return "\n    ".join(tags)


