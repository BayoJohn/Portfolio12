def article_sidebar(post, published, featured):
    current = post["url"]
    candidates = {item["url"]: item for item in published if item["url"] != current and not item.get("draft")}
    # Leave room for related reading when the catalogue is small.
    pick_limit = min(2, max(1, len(candidates) - 3))
    pick_urls = dict.fromkeys(item["url"] for item in featured if item["url"] in candidates)
    picks = [candidates.pop(url) for url in list(pick_urls)[:pick_limit]]
    tags = {tag.casefold() for tag in post.get("categories", [])}
    category = post["category"].casefold()
    collection = current.split("/", 1)[0]

    def relevance(item):
        shared = tags.intersection(tag.casefold() for tag in item.get("categories", []))
        return len(shared), item["category"].casefold() == category, item["url"].startswith(collection + "/")

    related = sorted(candidates.values(), key=relevance, reverse=True)[:3]
    topic_links = []
    for route in ("blog", "cybersecurity", "ai", "reviews", "software", "academy"):
        href = "../../" + (route if route.startswith("#") else route + "/")
        topic_links.append(f'<li><a href="{href}">{escape(HEADER_NAV[route])}</a></li>')
    return template("article-sidebar").substitute(
        picks=sidebar_stories("Editor’s Picks", picks, thumbnails=True),
        related=sidebar_stories("Related Stories", related),
        topics="".join(topic_links),
    ).rstrip()


def article(post, collection, posts, page=page, *, published=None, featured=()):
    intro = post.get("introduction", post["excerpt"])
    tags = post.get("categories", [])
    editorial = published is not None
    cover = article_cover(post, editorial=editorial)
    sources = (
        reading_links("Sources", cited_links(post.get("sources", [])),
                        css_class="reading-references")
        + reading_links("Official advisories", cited_links(post.get("security", {}).get("advisories", [])),
                        css_class="reading-references")
        + reading_links("Related resources", cited_links(post.get("tutorial", {}).get("resources", [])),
                        css_class="reading-references")
    )
    md = markdown.Markdown(
        extensions=["fenced_code", "tables", "toc", "admonition", ReadingExtension()]
        + ([] if post.get("managed") else ["attr_list"]),
        extension_configs={"toc": {"toc_depth": "2-4"}},
    )
    if post.get("managed"):
        md.preprocessors.deregister("html_block")
        md.inlinePatterns.deregister("html")
        md.treeprocessors.register(ManagedLinks(md), "managed_links", 1)
    body = md.convert(post["body"])
    show_toc = len(md.toc_tokens) >= 3 or post.get("articleType") == "tutorial"
    toc = article_toc(md.toc_tokens) if show_toc and md.toc_tokens else ""
    reading_time = reading_duration(post)
    author = escape(post["author"])
    if url := author_url(post):
        href = "../../about/" if url == ORIGIN + "about/" else url
        author = f'<a href="{escape(href)}">{author}</a>'
    bio = post.get("authorBio") or ("IT Help Desk professional based in Lagos, Nigeria." if post["author"] == AUTHOR else "")
    canonical = ORIGIN + post["url"]
    email = "mailto:?" + urlencode({"subject": post["title"], "body": canonical}, quote_via=quote)
    index = posts.index(post)
    adjacent = []
    for label, offset, rel in (("Newer article", -1, "prev"), ("Older article", 1, "next")):
        position = index + offset
        if 0 <= position < len(posts):
            item = posts[position]
            adjacent.append(
                f'<a rel="{rel}" href="../../{item["url"]}"><span class="reading-label">{label}</span>'
                f'<strong>{escape(item["title"])}</strong></a>'
            )
    topic_items = "".join(f'<li>{escape(tag)}</li>' for tag in tags)
    topics = f'<section class="reading-topics"><h2>Topics</h2><ul>{topic_items}</ul></section>' if topic_items else ""
    kind = ARTICLE_TYPES.get(post.get("articleType", ""))
    content = template("article").substitute(
        collection=escape(NAV[collection]), category=escape(post["category"]), title=escape(post["title"]),
        type_label=f' <span class="reading-type">{kind}</span>' if kind else "",
        summary=escape(intro), author=author, author_bio=f'<p>{escape(bio)}</p>' if bio else "",
        publication=f'<span>Published {post_date(post)}</span>' if post.get("dateTime") else "",
        reading_time=escape(reading_time),
        updated=f'<span>Updated {date_markup(date.fromisoformat(post["updatedTime"]))}</span>' if post.get("updatedTime") else "",
        layout_class=" reading-layout-with-sidebar" if editorial else "",
        standalone_cover=cover if not editorial else "", cover=cover if editorial else "", toc=toc,
        sidebar=article_sidebar(post, published, featured) if editorial else "",
        body=body, facts=article_facts(post),
        topics=topics,
        sources=sources,
        adjacent='<nav class="reading-adjacent" aria-label="Adjacent articles">' + "".join(adjacent) + '</nav>' if adjacent else "",
        canonical=escape(canonical), email_link=escape(email),
    ).rstrip()
    page(post["url"], post["title"], post.get("seoDescription") or post["excerpt"], content, post)


def newsroom_topic(value):
    return re.sub(r"[\W_]+", "", value.casefold())


def newsroom_post_topics(post):
    return " ".join(dict.fromkeys(filter(None, map(
        newsroom_topic, [post["category"], *post.get("categories", [])]
    ))))


def newsroom_filter_links(topics):
    links = ['<li><a href="./" data-newsroom-topic="">All News</a></li>']
    for key, label in topics.items():
        url = "?" + urlencode({"topic": key})
        links.append(f'<li><a href="{escape(url)}" data-newsroom-topic="{escape(key)}">{escape(label)}</a></li>')
    return "<ul>" + "".join(links) + "</ul>"


def newsroom_story(post, *, variant, heading=None, summary=None):
    compact = variant in {"top", "sidebar"}
    sizes = {
        "lead": "(min-width: 1350px) 800px, (min-width: 780px) 60vw, 92vw",
        "feature": "(min-width: 1350px) 610px, (min-width: 640px) 44vw, 92vw",
        "row": "(max-width: 639px) 100px, 168px",
    }
    photo = "" if compact else image(
        post, "newsroom-image", priority=variant == "lead", sizes=sizes[variant]
    )
    title = escape(post["title"])
    url = "../" + escape(post["url"])
    summary = "" if compact else (
        f'<p class="newsroom-summary">{escape(summary or post.get("newsroomExcerpt") or post["excerpt"])}</p>'
    )
    byline = f'<span>{escape(post["author"])}</span>' if variant == "lead" else ""
    meta = post_date(post) + byline
    heading = heading or ("h4" if variant == "row" or compact else "h3")
    return (
        photo + '<div class="newsroom-story-copy">'
        f'<p class="newsroom-category">{escape(post["category"])}</p>'
        f'<{heading}><a href="{url}">{title}</a></{heading}>' + summary
        + (f'<p class="newsroom-meta">{meta}</p>' if meta else "") + '</div>'
    )


