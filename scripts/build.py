    notes = "".join(
        f'<li>{date_markup(date.fromisoformat(item["date"]))} <span>{escape(item["note"])}</span></li>'
        for item in corrections
    )
    history = f'<h2>Corrections</h2><ul>{notes}</ul>' if notes else ""
    report = contact_url(f'Correction: {post["title"]}', f'Article: {ORIGIN}{post["url"]}')
    return (
        '<section class="reading-corrections" aria-label="Corrections and feedback">'
        f'{history}<p><a href="{escape(report)}">Report a correction</a> · '
        '<a href="../../corrections/">Corrections policy</a></p></section>'
    )


