"""Build static pages from the site templates and Markdown collections."""
from datetime import date
from html import escape
import json
from pathlib import Path
import re
from string import Template
from xml.sax.saxutils import escape as xml_escape

import markdown

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://stackedbybayo.site/"
GENERATED = "<!-- Generated by scripts/build.py -->"
NAV = {
    "": "Home",
    "academy": "Tech Academy",
    "blog": "Blog",
    "reviews": "Tech Reviews",
    "projects": "Projects",
    "about": "About",
    "contact": "Contact",
}
COLLECTIONS = {
    "academy": ("Beginner-friendly guides to computers, networking, operating systems, and IT troubleshooting.",
                "There are no published guides yet."),
    "blog": ("Troubleshooting lessons, hands-on projects, and notes from my technology learning journey.",
             "There are no published posts yet."),
    "reviews": ("Practical reviews of technology I’ve used, with context on what I tested and who it might suit.",
                "There are no published reviews yet."),
}


def template(name):
    return Template((ROOT / "templates" / f"{name}.html").read_text(encoding="utf-8"))


def metadata(route, title, description, post=None):
    url = ORIGIN + route
    tags = [
        f'<link rel="canonical" href="{escape(url)}">',
        f'<meta property="og:url" content="{escape(url)}">',
        f'<meta property="og:title" content="{escape(title)}">',
        f'<meta property="og:description" content="{escape(description)}">',
        '<meta property="og:site_name" content="StackedByBayo">',
        f'<meta property="og:type" content="{"article" if post else "website"}">',
    ]
    if post:
        tags.append(f'<meta property="article:published_time" content="{post["dateTime"]}">')
        data = {"@context": "https://schema.org", "@type": "BlogPosting",
                "headline": title, "description": description, "mainEntityOfPage": url,
                "datePublished": post["dateTime"],
                "author": {"@type": "Person", "name": "Omobayonle Ogundele", "url": ORIGIN + "about/"}}
        if post.get("image"):
            tags.append(f'<meta property="og:image" content="{escape(post["image"])}">')
            data["image"] = post["image"]
        tags.append('<script type="application/ld+json">' + json.dumps(data).replace("<", "\\u003c") + "</script>")
    return "\n    ".join(tags)


def navigation(root, active, article_page=False, *, header=False):
    routes = ("", "about", "academy", "blog", "reviews", "projects", "contact") if header else NAV
    current = "location" if article_page else "page"
    return "\n            ".join(
        f'<a href="{root + (route + "/" if route else "") or "./"}"'
        + (f' class="active" aria-current="{current}"' if route == active else "")
        + f'>{NAV[route]}</a>'
        for route in routes
    )


def footer(root):
    return (
        '<footer class="blog-footer publication-footer"><div class="blog-container">'
        f'<p><strong>StackedByBayo</strong><br>© {date.today().year} StackedByBayo</p>'
        f'<nav aria-label="Footer navigation">{navigation(root, None)}</nav>'
        '<nav aria-label="Social links"><a href="https://github.com/BayoJohn">GitHub</a>'
        '<a href="https://www.linkedin.com/in/bayo123/">LinkedIn</a>'
        '<a href="mailto:ogundelebayo8@gmail.com">Email</a></nav></div></footer>'
    )


def write(route, html):
    target = ROOT / (route if route == "404.html" else route + "index.html")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html.replace("<!doctype html>", "<!doctype html>\n" + GENERATED, 1), encoding="utf-8")


def page(route, title, description, content, post=None):
    missing = route == "404.html"
    active = None if missing else route.split("/", 1)[0]
    root = "/" if missing else "../" * route.count("/") or "./"
    seo = '<meta name="robots" content="noindex">' if missing else metadata(route, title, description, post)
    display_font = (
        '    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Instrument+Serif&amp;display=swap">\n'
        if not route else ""
    )
    write(route, template("page").substitute(
        root=root, title=escape(f"{title} | StackedByBayo" if route else f"StackedByBayo | {title}"),
        description=escape(description),
        metadata=seo, navigation=navigation(root, active, bool(post), header=True), display_font=display_font,
        footer=footer(root), content=content, main_class="article-main" if post else "platform-main",
    ))


def read_posts(collection):
    posts = []
    for path in sorted((ROOT / "content" / collection).glob("*.md")):
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", path.stem):
            raise ValueError(f"Invalid article slug in {path.name}")
        try:
            first, front_matter, body = path.read_text(encoding="utf-8").split("---\n", 2)
            if first:
                raise ValueError("Front matter must start the file")
            post = json.loads(front_matter)
            if post.get("draft"):
                continue
            for field in ("title", "category", "dateTime", "excerpt"):
                if not isinstance(post[field], str) or not post[field].strip():
                    raise ValueError(f"{field} must be a non-empty string")
            if not body.strip():
                raise ValueError("Article body is empty")
            published = date.fromisoformat(post["dateTime"])
            post["dateTime"] = published.isoformat()
        except (KeyError, ValueError, TypeError) as error:
            raise ValueError(f"{path}: {error}") from error
        post.update(url=f"{collection}/{path.stem}/", body=body, date=published)
        posts.append(post)
    return sorted(posts, key=lambda post: post["date"], reverse=True)


def post_date(post):
    published = post["date"]
    return f'<time datetime="{published.isoformat()}">{published:%b} {published.day}, {published.year}</time>'


def image(post, css_class):
    if not post.get("image"):
        return ""
    responsive = ""
    if css_class == "platform-card-image" and post["image"].startswith("https://images.unsplash.com/"):
        small, medium = (escape(re.sub(r"([?&]w=)\d+", rf"\g<1>{width}", post["image"]))
                         for width in (480, 800))
        if small != medium:
            responsive = f'srcset="{small} 480w, {medium} 800w" sizes="(max-width: 767px) 90vw, (max-width: 1050px) 45vw, 360px" '
    return (f'<img class="{css_class}" src="{escape(post["image"])}" {responsive}'
            f'alt="{escape(post.get("imageAlt", ""))}" loading="lazy" decoding="async">')


def card(post, root):
    return (
        f'<article class="article-card">{image(post, "platform-card-image")}'
        f'<div class="article-content"><div class="post-meta"><span>{escape(post["category"])}</span> '
        f'{post_date(post)}</div><h3><a class="card-link" href="{root}{post["url"]}">'
        f'{escape(post["title"])}</a></h3><p>{escape(post["excerpt"])}</p></div></article>'
    )


def section(title, intro, body=""):
    return (f'<section class="blog-intro platform-intro"><div class="blog-container">'
            f'<h1>{escape(title)}</h1><p>{escape(intro)}</p></div></section>'
            f'<div class="blog-container platform-content">{body}</div>')


def article(post, collection, posts):
    title = escape(post["title"])
    intro = post.get("introduction", post["excerpt"])
    tags = set(post.get("categories", []))
    related = [item for item in posts if item is not post and
               (item["category"] == post["category"] or tags.intersection(item.get("categories", [])))]
    related_links = "".join(f'<li><a href="../../{item["url"]}">{escape(item["title"])}</a></li>'
                            for item in related[:3])
    reading_time = f' · {escape(post["readTime"])}' if post.get("readTime") else ""
    body = markdown.markdown(post["body"], extensions=["fenced_code", "tables"])
    content = (
        f'<article class="article-shell"><a class="back-to-blog" href="../">Back to {NAV[collection]}</a>'
        f'<header class="article-header"><p class="article-eyebrow">{escape(post["category"])} · '
        f'{post_date(post)}{reading_time}</p><h1>{title}</h1>'
        f'<p class="article-deck">{escape(intro)}</p><p>By Omobayonle Ogundele</p></header>'
        f'{image(post, "article-cover platform-cover")}<div class="article-body">{body}'
        + (f'<h2>Related reading</h2><ul>{related_links}</ul>' if related_links else "")
        + '</div></article>'
    )
    page(post["url"], post["title"], intro, content, post)


def main():
    routes = [f"{route}/" if route else "" for route in NAV]
    collections = {name: read_posts(name) for name in COLLECTIONS}
    for name, posts in collections.items():
        intro, empty = COLLECTIONS[name]
        if name == "blog":
            featured = next((post for post in posts if post.get("featured")), None)
            remaining = [post for post in posts if post is not featured]
            listing = (
                f'<section class="platform-feature"><h2>Featured article</h2>{card(featured, "../")}</section>'
                if featured else ""
            )
            if remaining:
                listing += '<h2>Recent articles</h2><div class="article-grid">' + "".join(
                    card(post, "../") for post in remaining
                ) + '</div>'
        else:
            listing = "".join(
                f'<section><h2>{escape(category)}</h2><div class="article-grid">'
                + "".join(card(post, "../") for post in posts if post["category"] == category)
                + '</div></section>'
                for category in dict.fromkeys(post["category"] for post in posts)
            )
        if not listing:
            suggestion = '<p><a href="../blog/">Read the blog</a></p>' if name != "blog" else ""
            listing = f'<div class="publication-empty"><p>{escape(empty)}</p>{suggestion}</div>'
        page(name + "/", NAV[name], intro, section(NAV[name], intro, listing))
        for post in posts:
            article(post, name, posts)
            routes.append(post["url"])

    about = (
        '<div class="article-body"><h2>My work in IT support</h2>'
        '<p>I work in IT Help Desk, where I help people troubleshoot everyday technology problems. '
        'I’m interested in the fundamentals behind those problems, from hardware and operating systems to networking.</p>'
        '<h2>What I’m learning</h2><p>I’m learning cloud computing and DevOps through hands-on projects. '
        'I share what I build, what goes wrong, and what I learn from fixing it.</p>'
        '<h2>Why I write</h2><p>I want to make technical ideas easier to understand and give beginners a practical place to start.</p>'
        '<p><a href="../blog/">Read my blog</a> · <a href="../projects/">Explore my projects</a></p></div>'
    )
    for route, title, intro, body in [
        ("about", "About Bayo", "I’m Omobayonle Ogundele, an IT Help Desk professional based in Lagos, Nigeria.", about),
        ("projects", "Projects", "Hands-on projects exploring Linux, cloud services, automation, and DevOps.", template("projects").template),
        ("contact", "Contact", "Get in touch with Bayo.", template("contact").template),
    ]:
        page(route + "/", title, intro, section(title, intro, body))

    project_cards = re.findall(
        r'<article class="project-card".*?</article>', template("projects").template, re.DOTALL
    )
    recent = sorted((post for posts in collections.values() for post in posts),
                    key=lambda post: post["date"], reverse=True)[:3]
    latest = ('<div class="article-grid">' + "".join(card(post, "./") for post in recent) + '</div>'
              if recent else '<p>There are no published articles yet.</p>')
    home = template("home").substitute(
        selected_projects="".join(project_cards[:2]), recent=latest,
        ticker_topics="TECHNOLOGY • IT SUPPORT • COMPUTERS • NETWORKING • REVIEWS • DEVOPS",
    )
    page("", "Technology, Explained Simply",
         "Practical technology guides, IT troubleshooting lessons, hands-on projects, and reviews by Bayo Ogundele.",
         home)
    page("404.html", "Page not found", "Find your way back to StackedByBayo.",
         section("Page not found", "The page you requested may have moved.",
                 '<div class="publication-actions"><a class="publication-button primary" href="/">Go to the homepage</a>'
                 '<a class="publication-button" href="/blog/">Browse the blog</a></div>'))
    published_pages = {ROOT / route / "index.html" for route in routes}
    for collection in collections:
        for generated_page in (ROOT / collection).glob("*/index.html"):
            if generated_page not in published_pages and generated_page.read_text(encoding="utf-8").startswith(
                "<!doctype html>\n" + GENERATED + "\n"
            ):
                generated_page.unlink()

    urls = "\n".join(f"  <url><loc>{xml_escape(ORIGIN + route)}</loc></url>" for route in routes)
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + urls + "\n</urlset>\n", encoding="utf-8",
    )


if __name__ == "__main__":
    main()
