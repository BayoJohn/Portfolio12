def web_url(value):
    parts = urlsplit(value)
    return value if parts.scheme in {"https", "http"} and parts.hostname else ""


def author_url(post):
    profiles = {AUTHOR: FOUNDER_ROUTE, PUBLICATION: "about/"}
    profile = profiles.get(post["author"])
    return web_url(post.get("authorURL", "")) or (ORIGIN + profile if profile else "")


def image_credit(post):
    url = post["image"]
    credit = escape(post.get("imageCredit", ""))
    credit_url = post.get("imageCreditURL", "")
    if not credit and url.startswith("https://images.unsplash.com/"):
        credit = "Illustrative photo via Unsplash"
        credit_url = url
    if credit and (link := web_url(credit_url)):
        credit = f'<a href="{escape(link)}">{credit}</a>'
    if credit and (license_url := web_url(post.get("imageLicenseURL", ""))):
        credit += f' · <a href="{escape(license_url)}">{escape(post.get('imageLicense', 'Image license'))}</a>'
    return credit


def article_cover(post, *, editorial):
    if not post.get("image"):
        return ""
    caption = " · ".join(filter(None, (escape(post.get("imageCaption", "")), image_credit(post))))
    sizes = ("(min-width: 1440px) 890px, (min-width: 1060px) 64vw, (min-width: 780px) 720px, 94vw"
             if editorial else "(max-width: 1230px) 94vw, 1160px")
    return (
        '    <figure class="reading-cover">'
        + image(post, "reading-cover-image", priority=True, sizes=sizes)
        + (f'<figcaption>{caption}</figcaption>' if caption else "") + '</figure>'
    )


def article_toc(tokens):
    def links(items):
        return '<ol>' + "".join(
            f'<li><a href="#{escape(quote(item["id"]))}">{escape(unescape(item["name"]))}</a>'
            + (links(item["children"]) if item["children"] else "") + '</li>'
            for item in items
        ) + '</ol>'

    return ('<aside class="reading-toc"><details><summary>On this page</summary>'
            '<nav aria-label="Table of contents">' + links(tokens) + '</nav></details></aside>')


def reading_links(title, links, *, css_class, heading="h2"):
    if not links:
        return ""
    items = "".join(f'<li><a href="{escape(url)}">{escape(label)}</a></li>' for label, url in links)
    return f'<section class="{css_class}"><{heading}>{escape(title)}</{heading}><ul>{items}</ul></section>'


def cited_links(refs):
    return [(f'{ref["label"]} ({ref["date"]})' if ref.get("date") else ref["label"], url)
            for ref in refs if (url := web_url(ref["url"]))]


def article_facts(post):
    sections = []
    for key, title, labels in ARTICLE_FACTS:
        fields = post.get(key, {})
        rows = []
        for field, label in labels.items():
            value = fields.get(field)
            if not value:
                continue
            if isinstance(value, list):
                text = '<ul>' + "".join(f'<li>{escape(item)}</li>' for item in value) + '</ul>'
            else:
                text = escape(value)
            if field == "severity":
                text += f' <a href="{escape(fields["severitySource"])}">Rating source</a>'
            rows.append(f'<dt>{label}</dt><dd>{text}</dd>')
        if rows:
            sections.append(f'<section class="reading-facts"><h2>{title}</h2><dl>{"".join(rows)}</dl></section>')
    return "".join(sections)


